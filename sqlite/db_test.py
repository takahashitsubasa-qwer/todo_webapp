import sqlite3

# =====================================================================
# STEP 1: データベースに接続する
# =====================================================================
# 'app.db' というファイルが自動で作られます
conn = sqlite3.connect('app.db')

# SQLを実行するための「作業員（カーソル）」を呼び出します
cursor = conn.cursor()


# =====================================================================
# STEP 2: テーブル（表）を作る
# =====================================================================
# usersという名前のテーブルを作ります
# id (自動で連番), name (名前), age (年齢) の3つの列を持ちます
cursor.execute('''
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    age INTEGER
)
''')
print("1. テーブルの作成（または確認）が完了しました。")


# =====================================================================
# STEP 3: データを追加する (INSERT)
# =====================================================================
# 練習用に3人のユーザーデータを追加してみます
# 安全にデータを追加するために、値の部分は「?」にして後から流し込みます
users_data = [
    ('タロウ', 25),
    ('ハナコ', 30),
    ('ジロウ', 18)
]

# executemany を使うと、複数のデータを一気に挿入できます
cursor.executemany('INSERT INTO users (name, age) VALUES (?, ?)', users_data)
print(f"2. {len(users_data)}人のデータを追加しました。")


# =====================================================================
# STEP 4: データを検索して表示する (SELECT)
# =====================================================================
# usersテーブルから全てのデータ（全列）を引っ張ってきます
cursor.execute('SELECT id, name, age FROM users')

# 検索結果をすべて取得して rows に入れます
rows = cursor.fetchall()

print("\n--- 【現在のユーザー一覧】 ---")
for row in rows:
    # rowの中身は (id, name, age) というタプル（データの塊）になっています
    print(f"ID: {row[0]} | 名前: {row[1]} | 年齢: {row[2]}歳")
print("-------------------------------\n")


# =====================================================================
# STEP 5: 変更を保存して接続を閉じる
# =====================================================================
# commit() を呼ばないと、追加したデータが完全に保存されません
conn.commit()

# 最後に必ずお片付け（接続を閉じる）をします
conn.close()
print("3. データベースを安全に閉じました。すべての処理が成功です！")